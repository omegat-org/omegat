"""Render editor-colors.svg: every Styles.EditorColor value of the bundled
flat themes, light and dark side by side, once in enum order and once sorted
by hue.

Input CSVs come from ColorDump.java (same directory). From a built
distribution (build/install/OmegaT):

  javac -cp "OmegaT.jar:lib/*:modules/theme-omegat.jar" -d /tmp ColorDump.java
  java -Djava.awt.headless=true -cp "/tmp:OmegaT.jar:lib/*:modules/theme-omegat.jar" \
      ColorDump org.omegat.gui.theme.DefaultFlatLightTheme > colors-Light.csv
  java -Djava.awt.headless=true -cp "/tmp:OmegaT.jar:lib/*:modules/theme-omegat.jar" \
      ColorDump org.omegat.gui.theme.DefaultFlatDarkTheme > colors-Dark.csv
  ./generate_editor_colors_svg.py colors-Light.csv colors-Dark.csv editor-colors.svg
"""
